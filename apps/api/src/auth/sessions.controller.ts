import { Body, Controller, Get, Post } from '@nestjs/common';
import { z } from 'zod';
import { parseEd25519PublicKey } from '@agenttrust/identity';
import { IdPrefix, newId } from '@agenttrust/shared';
import { AgentWorkload, CurrentAgent, CurrentUser, Human, type AgentPrincipal, type HumanPrincipal } from '../auth/principal';
import { AuditService } from '../audit/audit.service';
import { Errors } from '../common/errors';
import { PrismaService } from '../common/prisma.service';
import { ZodPipe } from '../common/validation';

const CreateSession = z
  .object({
    /** Ephemeral Ed25519 public key generated by the agent runtime for this session. */
    publicKeyPem: z.string().min(40).max(1000),
    ttlSeconds: z.number().int().min(60).max(3600).default(900),
  })
  .strict();

/**
 * Short-lived agent sessions.
 *
 * The workload credential (long-lived, ideally held by a sidecar/KMS and never
 * visible to the LLM) signs a request to mint a session bound to a fresh
 * ephemeral key. Only session keys can request authorizations or execute
 * payments, so a key stolen from the agent's runtime is useful for minutes,
 * not forever, and stops working the moment the agent is suspended/revoked.
 *
 * Production: the workload proves itself with a workload-identity attestation
 * (SPIFFE JWT-SVID, AWS IAM / GCP / Azure workload identity OIDC token) in
 * addition to, or instead of, a registered key. See WorkloadIdentityVerifier
 * in docs/SECURITY.md.
 */
@Controller('v1')
export class SessionsController {
  constructor(
    private readonly prisma: PrismaService,
    private readonly audit: AuditService,
  ) {}

  @Post('agent-sessions')
  @AgentWorkload()
  async create(@CurrentAgent() agent: AgentPrincipal, @Body(new ZodPipe(CreateSession)) body: z.infer<typeof CreateSession>) {
    if (agent.agentStatus !== 'active') throw Errors.forbidden('AGENT_NOT_ACTIVE', `Agent is ${agent.agentStatus}`);
    try {
      parseEd25519PublicKey(body.publicKeyPem);
    } catch {
      throw Errors.invalid('publicKeyPem must be an Ed25519 public key in SPKI PEM format');
    }
    const credential = await this.prisma.agentCredential.findUnique({ where: { id: agent.credentialId } });
    const ttlMs = body.ttlSeconds * 1000;
    // A session can never outlive its workload credential.
    const expiresAt = new Date(Math.min(Date.now() + ttlMs, credential?.expiresAt?.getTime() ?? Number.MAX_SAFE_INTEGER));
    const id = newId(IdPrefix.session);
    return this.prisma.tx(async (tx) => {
      await tx.agentSession.create({
        data: { id, organizationId: agent.organizationId, agentId: agent.agentId, credentialId: agent.credentialId, publicKeyPem: body.publicKeyPem, expiresAt },
      });
      await this.audit.append(tx, {
        organizationId: agent.organizationId, actorType: 'agent', actorId: agent.agentId, eventType: 'agent.session_created', subjectId: id,
        payload: { credentialId: agent.credentialId, expiresAt: expiresAt.toISOString() },
      });
      return { sessionId: id, expiresAt: expiresAt.toISOString() };
    });
  }

  /** Security alerts (auth-failure probing, fraud signals, repeated denials, reconciliation needs, suspensions). */
  @Get('alerts')
  @Human('admin', 'approver')
  async alerts(@CurrentUser() user: HumanPrincipal) {
    const events = await this.prisma.auditEvent.findMany({
      where: { organizationId: user.organizationId, eventType: { in: ['alert.raised', 'agent.auto_suspended'] } },
      orderBy: { sequence: 'desc' },
      take: 200,
    });
    return {
      alerts: events.map((e) => ({ id: e.id, type: e.eventType, subjectId: e.subjectId, createdAt: e.createdAt.toISOString(), ...(e.payload as object) })),
    };
  }
}
