/**
 * Generates a local .env with fresh development secrets.
 * Never commit .env. Production secrets come from a secret manager / KMS.
 */
import { randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { generateEd25519KeyPair } from '../packages/identity/src/keys';

const target = path.resolve(__dirname, '..', '.env');
if (existsSync(target) && !process.argv.includes('--force')) {
  console.log('.env already exists (use --force to regenerate).');
  process.exit(0);
}

const { privateKeyPem } = generateEd25519KeyPair();
const hex = (n: number) => randomBytes(n).toString('hex');

const env = `# Generated by scripts/setup-env.ts. DEVELOPMENT ONLY. Do not commit.
DATABASE_URL=postgresql://agenttrust@localhost:54329/agenttrust
TEST_DATABASE_URL=postgresql://agenttrust@localhost:54329/agenttrust_test
PORT=4000
AGENTTRUST_SIGNING_KEY_ID=dev-${hex(4)}
AGENTTRUST_SIGNING_KEY_PEM_B64=${Buffer.from(privateKeyPem).toString('base64')}
AGENTTRUST_PAYEE_PEPPER=${hex(32)}
AGENTTRUST_BOOTSTRAP_TOKEN=${hex(24)}
AGENTTRUST_DEV_AUTH=true
AGENTTRUST_DEV_AUTH_SECRET=${hex(32)}
AGENTTRUST_SANDBOX_WEBHOOK_SECRET=${hex(32)}
AGENTTRUST_SANDBOX_SIGNUP=true
`;

writeFileSync(target, env, { mode: 0o600 });
console.log(`Wrote ${target}`);
